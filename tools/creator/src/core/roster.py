"""The playable figures a custom character can be based on, and where each one's model lives in the game.

src/assets/roster.json (regenerated by tools/build_roster.py) lists every Toy Box avatar with its grid data
(sku, icon, progression tree) and its .dnax. The model path is read from that .dnax at run time:
'characters/<dir>/<model>' strings, preferring the one named after the .dnax itself.
"""
import json
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from src.core import luac
from src.core.game_files import GameFileError, GameInstall
from src.core.paths import ASSETS_DIR

ROSTER_PATH = ASSETS_DIR / "roster.json"
_MODEL_PATH = re.compile(rb"^characters/([A-Za-z0-9_]+)/([A-Za-z0-9_]+)$", re.I)


@dataclass(frozen=True)
class RosterEntry:
    actor: str
    display_name: str
    sku: str
    icon: str
    progression_tree: str
    franchise: str
    dnax: str

    @property
    def dnax_stem(self) -> str:
        return Path(self.dnax).stem.lower()


@lru_cache(maxsize=1)
def load_roster() -> tuple[RosterEntry, ...]:
    rows = json.loads(ROSTER_PATH.read_text(encoding="utf-8"))
    return tuple(RosterEntry(**row) for row in rows)


def find_entry(actor: str) -> RosterEntry:
    for entry in load_roster():
        if entry.actor.lower() == actor.lower():
            return entry
    raise KeyError(actor)


def dnax_strings(data: bytes) -> list[bytes]:
    """String constants of a .dnax: compiled Lua, or (on hand-edited installs) Lua source."""
    if data.startswith(luac.HEADER[:4]):
        return luac.string_constants(luac.load(data))
    return [m.encode("latin-1") for m in re.findall(r'"([^"\r\n]*)"', data.decode("latin-1"))]


def model_candidates(data: bytes) -> list[tuple[str, str]]:
    out = []
    for s in dnax_strings(data):
        m = _MODEL_PATH.match(s)
        if m and (m[1].decode().lower(), m[2].decode().lower()) not in out:
            out.append((m[1].decode().lower(), m[2].decode().lower()))
    return out


def resolve_model(entry: RosterEntry, game: GameInstall) -> tuple[str, str]:
    """(folder, model) of the figure's default model, e.g. ('ts_woody', 'ts_woody')."""
    stem = entry.dnax_stem
    if game.has_model(stem, stem):
        return stem, stem
    # *_pieces is the break-apart model shown when the figure is knocked out, never the playable one.
    candidates = [c for c in model_candidates(game.dnax(entry.dnax).read_bytes()) if not c[1].endswith("_pieces")]
    ranked = sorted(candidates, key=lambda c: (c[1] != stem, c[0] != c[1]))
    for folder, model in ranked:
        if game.has_model(folder, model):
            return folder, model
    raise GameFileError(f"{entry.actor}: no model found from {entry.dnax}")
