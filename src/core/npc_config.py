"""Configuration and runtime export generator for Enemies and NPCs."""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path


class EntityType(str, Enum):
    AVATAR = "Avatar"
    ENEMY = "Enemy"
    ALLY = "Ally"
    NPC = "NPC"


class Faction(str, Enum):
    HEROES = "Heroes"
    ENEMIES = "Enemies"
    NEUTRAL = "Neutral"
    TOWNSPERSON = "Townsperson"


@dataclass
class EntityConfig:
    entity_type: EntityType = EntityType.AVATAR
    faction: Faction = Faction.HEROES
    max_health: int = 100
    base_damage: int = 25
    move_speed: float = 1.0
    aggro_range: float = 15.0
    behavior: str = "Hostile"  # Hostile, Passive, Follower, Patrol
    animations: dict[str, str] = field(default_factory=lambda: {
        "idle": "Idle",
        "walk": "Walk",
        "attack": "Attack",
    })

    @property
    def is_player(self) -> bool:
        return self.entity_type == EntityType.AVATAR

    @property
    def is_enemy(self) -> bool:
        return self.entity_type == EntityType.ENEMY

    @property
    def is_npc_or_ally(self) -> bool:
        return self.entity_type in (EntityType.ALLY, EntityType.NPC)

    def summary(self) -> str:
        if self.is_player:
            return "Playable Avatar (Player Hero)"
        if self.is_enemy:
            return f"Enemy [Health: {self.max_health}, Damage: {self.base_damage}, Behavior: {self.behavior}]"
        return f"Ally / NPC [Faction: {self.faction.value}, Health: {self.max_health}, Behavior: {self.behavior}]"

    def to_dict(self) -> dict:
        return {
            "entity_type": self.entity_type.value,
            "faction": self.faction.value,
            "max_health": self.max_health,
            "base_damage": self.base_damage,
            "move_speed": self.move_speed,
            "aggro_range": self.aggro_range,
            "behavior": self.behavior,
            "animations": self.animations,
        }

    @classmethod
    def from_dict(cls, data: dict) -> EntityConfig:
        return cls(
            entity_type=EntityType(data.get("entity_type", EntityType.AVATAR.value)),
            faction=Faction(data.get("faction", Faction.HEROES.value)),
            max_health=int(data.get("max_health", 100)),
            base_damage=int(data.get("base_damage", 25)),
            move_speed=float(data.get("move_speed", 1.0)),
            aggro_range=float(data.get("aggro_range", 15.0)),
            behavior=str(data.get("behavior", "Hostile")),
            animations=dict(data.get("animations", {"idle": "Idle", "walk": "Walk", "attack": "Attack"})),
        )


def generate_lua_spawner_code(ident_slug: str, actor: str, display_name: str, config: EntityConfig) -> str:
    """Generate CrabeMenu / runtime registration Lua code for Enemy and NPC entities."""
    lua_name = display_name.replace("\\", "\\\\").replace('"', '\\"')
    target_table = "Crabe.Enemies" if config.is_enemy else "Crabe.NPCs"

    anim_lines = "\n".join(f'        {k} = "{v}",' for k, v in config.animations.items())

    return (
        f"-- {display_name}: custom {config.entity_type.value} generated by Disney Infinity Creator.\n"
        f"Crabe = Crabe or {{}}\n"
        f"{target_table} = {target_table} or {{}}\n"
        f"Crabe.ModdedCharacters = Crabe.ModdedCharacters or {{}}\n"
        f"\n"
        f'local ACTOR = "{actor}"\n'
        f'local NAME = "{lua_name}"\n'
        f"\n"
        f"local function spawn(pos)\n"
        f"    pos = pos or {{ x = 0, y = 0, z = 0 }}\n"
        f'    print(string.format("Spawning {config.entity_type.value} %s (%s) at (%.1f, %.1f, %.1f)", NAME, ACTOR, pos.x or 0, pos.y or 0, pos.z or 0))\n'
        f'    if type(Game) == "table" and type(Game.SpawnActor) == "function" then\n'
        f'        return Game.SpawnActor(ACTOR, pos.x or 0, pos.y or 0, pos.z or 0)\n'
        f"    end\n"
        f'    return "Game.SpawnActor API not available; registered in actor pool."\n'
        f"end\n"
        f"\n"
        f'{target_table}["{ident_slug}"] = {{\n'
        f'    name = NAME,\n'
        f'    actor = ACTOR,\n'
        f'    type = "{config.entity_type.value}",\n'
        f'    faction = "{config.faction.value}",\n'
        f'    health = {config.max_health},\n'
        f'    damage = {config.base_damage},\n'
        f'    speed = {config.move_speed},\n'
        f'    behavior = "{config.behavior}",\n'
        f'    animations = {{\n'
        f'{anim_lines}\n'
        f'    }},\n'
        f'    spawn = spawn,\n'
        f'}}\n'
        f"\n"
        f'-- Also register in ModdedCharacters so CrabeMenu can list and preview it\n'
        f'Crabe.ModdedCharacters["{ident_slug}"] = {{\n'
        f'    name = NAME .. " ({config.entity_type.value})",\n'
        f'    action = spawn,\n'
        f'}}\n'
        f'print(string.format("[%s] {config.entity_type.value} %s registered successfully.", ACTOR, NAME))\n'
    )

