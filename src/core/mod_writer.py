def write_text_files(mod_dir: Path, ident: Identity, base: BaseCharacter,
                     entity_config: EntityConfig | None = None,
                     abilities: CharacterAbilities | None = None) -> None:
    cfg = entity_config or EntityConfig()
    abils = abilities or CharacterAbilities()
    bl, lname, name = base.actor_lower, ident.lower, ident.actor
    eff_progression = abils.get_effective_progression_tree(base)
    eff_combat_actor = abils.effective_combat_actor(base)

    manifest = {
        "manifestVersion": 1,
        "id": f"creator.{ident.slug.replace('_', '-')}",
        "name": ident.display_name,
        "version": "1.0.0",
        "description": f"Custom standalone character {ident.display_name} based on {base.actor}.",
        "minLoaderVersion": "0.2.0",
        "entry": f"{ident.slug}.lua",
        "character": {
            "name": ident.actor,
            "baseCharacter": base.actor,
            "displayName": ident.display_name,
            "icon": hud_name(ident.actor),
        },
        "entityType": cfg.entity_type.value,
        "faction": cfg.faction.value,
    }
    manifest = abils.apply_to_manifest(manifest, base)
    (mod_dir / "mod.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    lua_name = ident.display_name.replace("\\", "\\\\").replace('"', '\\"')
    if cfg.is_player:
        lua_content = (
            f"-- {ident.display_name}: custom character generated by Disney Infinity Creator.\n"
            f"-- Engine actor {name} (base {base.actor}, combat moveset from {eff_combat_actor}).\n"
            "-- The character is declared in mod.json (\"character\" block): CrabeLoader lists it under\n"
            "-- Heroes > Modded Characters. The sandbox forbids writing to the global Crabe table,\n"
            "-- so this script only logs.\n"
            f'print("[{name}] {lua_name} loaded (Combat: {eff_combat_actor}, Flight: {str(abils.can_fly).lower()}).")\n'
        )
    else:
        lua_content = generate_lua_spawner_code(ident.slug, name, ident.display_name, cfg)

    (mod_dir / f"{ident.slug}.lua").write_text(lua_content, encoding="utf-8")

    (mod_dir / "characters").mkdir(parents=True, exist_ok=True)
    (mod_dir / "characters" / f"{name}.lua").write_text(
        f"-- {name}: new actor declared for the Virtual Reader (clone of {base.actor}, combat {eff_combat_actor}).\n"
        "Crabe.VirtualReader.exposeCharacter({\n"
        f'    Name = "{name}",\n'
        f'    ProgressionTree = "{eff_progression}",\n'
        "})\n", encoding="utf-8")

    skill = mod_dir / "skilltrees"
    skill.mkdir(parents=True, exist_ok=True)

    if cfg.is_enemy:
        rec_type = "Enemy"
    elif cfg.is_npc_or_ally:
        rec_type = "NPC"
    else:
        rec_type = "Avatar"

    parms = abils.generate_parms_string(name, base, cfg)


    (skill / "ActorList.patch").write_text(
        f"-- Appends the {lname} actor to every ActorList that ships {bl}.\n"
        "-- No standard library in this Lua state: core syntax only.\n"
        'if Data and Data.DBName == "ActorList" and Data.Records then\n'
        "    local recs = Data.Records\n"
        "    local n = #recs\n"
        "    local i = 1\n"
        "    local hasBase = false\n"
        "    local hasClone = false\n"
        "    while i <= n do\n"
        "        local rec = recs[i]\n"
        "        if rec then\n"
        f'            if rec.Name == "{bl}" then hasBase = true end\n'
        f'            if rec.Name == "{lname}" then hasClone = true end\n'
        "        end\n"
        "        i = i + 1\n"
        "    end\n"
        "    if hasBase and not hasClone then\n"
        f'        recs[n + 1] = {{ Parms = "{parms}", Type = "{rec_type}", Name = "{lname}" }}\n'
        "    end\n"
        "end\n", encoding="utf-8")
    # DataMap keys the actor by its ActorList name and lists its .dnax ("DNA|characters/<dnax>") and, for some
    # figures, its model ("Entity|characters/<dir>/<model>"); the default costume is "<name>_default".
    dna_from = f"DNA|characters/{base.entry.dnax_stem}"
    entity_from = f"Entity|characters/{base.model_dir}/{base.model}"
    costumes = list(dict.fromkeys(f"{k}_default" for k in (bl, base.entry.dnax_stem, base.model)))
    lines = [
        f"-- Clones the {bl} preload entries (actor + default costume) for {lname},",
        "-- pointing the .dnax and the model at the clone's own files.",
        "-- No standard library in this Lua state: core syntax only.",
        "local function cloneFiles(files)",
        "    local out = {}",
        "    local i = 1",
        "    while files and i <= #files do",
        "        local v = files[i]",
        f'        if v == "{dna_from}" then v = "DNA|characters/{lname}/{lname}" end',
        f'        if v == "{entity_from}" then v = "Entity|characters/{lname}/{lname}" end',
        "        out[i] = v",
        "        i = i + 1",
        "    end",
        "    return out",
        "end",
        "local A = DataMap and DataMap.Actor",
        f'if A and A["{bl}"] and not A["{lname}"] then',
        f'    local src = A["{bl}"]',
        f'    A["{lname}"] = {{ Includes = src.Includes, Files = cloneFiles(src.Files) }}',
        "end",
        "local C = DataMap and DataMap.Costume",
        f'if C and not C["{lname}_default"] then',
    ]
    for k, key in enumerate(costumes):
        lines.append(f'    {"if" if k == 0 else "elseif"} C["{key}"] then')
        lines.append(f'        C["{lname}_default"] = {{ Files = cloneFiles(C["{key}"].Files) }}')
    lines += ["    end", "end"]
    (skill / "DataMap.patch").write_text("\n".join(lines) + "\n", encoding="utf-8")


def ship_motions_if_needed(base: BaseCharacter, game_dir: Path, mod_dir: Path) -> str:
    """The base's own animations live only inside its model archive. When that archive is disabled on this install
    (renamed .orig), ship its motion folders loose or the character slides without moving its legs."""
    archive = base.game_model_zip(game_dir)
    if archive.exists():
        return f"animations read from {archive.name} (present)"
    disabled = archive.with_name(archive.name + ".orig")
    if not disabled.exists():
        return f"animations: no {archive.name} in the game, relying on its loose motion files"
    with tempfile.TemporaryDirectory(prefix="dic_motions_") as tmp:
        subprocess.run([str(QUICKBMS), "-Y", str(BMS_SCRIPT), str(disabled), tmp],
                       check=True, capture_output=True, creationflags=_NO_WINDOW)
        motions = [p for p in Path(tmp).rglob("*") if p.is_file() and p.parent.name.lower() == "motions"]
        for m in motions:
            dst = mod_dir / "characters" / m.parent.parent.name.lower() / "motions"
            dst.mkdir(parents=True, exist_ok=True)
            shutil.copy2(m, dst / m.name.lower())
    return f"{len(motions)} {base.actor} animations shipped ({archive.name} is disabled on this install)"
