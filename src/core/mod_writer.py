@dataclass(frozen=True)
class Identity:
    """slug = mod folder / Lua key; actor = engine actor name of the clone (e.g. MAR_Mari)."""
    slug: str
    display_name: str
    actor: str

    @property
    def lower(self) -> str:
        return self.actor.lower()


def slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def default_actor(name: str) -> str:
    clean = re.sub(r"[^A-Za-z0-9]", "", name) or "Hero"
    return f"{clean[:3].upper().ljust(3, 'X')}_{clean[:4].capitalize().ljust(4, 'x')}"


def make_identity(display_name: str, actor: str, base: BaseCharacter, game_dir: Path) -> Identity:
    slug = slugify(display_name)
    if not slug:
        raise ValueError("give the character a name")
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]{2,31}", actor):
        raise ValueError("the actor name must be 3 to 32 characters (letters, digits, _) starting with a letter, "
                         "like MAR_Mari")
    if actor.lower() in {e.actor.lower() for e in load_roster()} or actor.lower() == base.model:
        raise ValueError(f"{actor} is already a figure of the game: pick another actor name")
    if (Path(game_dir) / "assets" / "characters" / actor.lower()).exists():
        raise ValueError(f"assets/characters/{actor.lower()} already exists in the game: pick another actor name")
    manifest = Path(game_dir) / "mods" / slug / "mod.json"
    if manifest.exists():
        try:
            owned = str(json.loads(manifest.read_text(encoding="utf-8")).get("id", "")).startswith("creator.")
        except ValueError:
            owned = False
        if not owned:
            raise ValueError(f"mods/{slug} already exists and was not made by Disney Infinity Creator: "
                             "pick another character name")
    for other in (Path(game_dir) / "mods").glob(f"*/characters/{actor.lower()}"):
        if other.parent.parent.name.lower() != slug:
            raise ValueError(f"actor {actor} already exists in mod '{other.parent.parent.name}': pick another name")
    return Identity(slug, display_name.strip(), actor)


def backup_existing(mod_dir: Path) -> Path | None:
    if not mod_dir.exists():
        return None
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    target = BACKUP_DIR / f"{mod_dir.name}_{time.strftime('%Y%m%d_%H%M%S')}"
    shutil.move(str(mod_dir), str(target))
    return target


from src.core.npc_config import EntityConfig, EntityType, generate_lua_spawner_code
